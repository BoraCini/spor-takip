const lower = (s) => String(s || '').toLocaleLowerCase('tr-TR');
const NAME_INDEX = Object.fromEntries(Object.keys(EX_MUSCLES).map((k) => [lower(k), k]));

// ex: { name, muscle, muscles? } → { primary: [], secondary: [] }
export function musclesOf(ex) {
  if (!ex) return { primary: [], secondary: [] };
  if (ex.muscles && Array.isArray(ex.muscles.primary)) return ex.muscles;
  const key = NAME_INDEX[lower(ex.name)];
  const m = (key && EX_MUSCLES[key]) || BY_GROUP[ex.muscle] || null;
  return m ? { primary: m[0], secondary: m[1] } : { primary: [], secondary: [] };
}

